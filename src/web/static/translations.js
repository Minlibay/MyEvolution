let currentLang = (() => { try { return localStorage.getItem('evosim_lang') || 'ru'; } catch(e) { return 'ru'; } })();

function t(key, ...args) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.ru;
  let str = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key]
           : (Object.prototype.hasOwnProperty.call(TRANSLATIONS.ru, key) ? TRANSLATIONS.ru[key] : key);
  for (let i = 0; i < args.length; i++) str = str.replace('{' + i + '}', args[i]);
  return str;
}

function setLang(lang) {
  currentLang = (lang === 'en') ? 'en' : 'ru';
  try { localStorage.setItem('evosim_lang', currentLang); } catch(e) {}
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-placeholder')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  // Update chip data-cmd values
  document.querySelectorAll('.agp-chip[data-cmd-key]').forEach(chip => {
    chip.dataset.cmd = t('cmd_val.' + chip.dataset.cmdKey);
  });
  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) langBtn.textContent = currentLang === 'ru' ? 'EN' : 'RU';
  document.documentElement.lang = currentLang;
}
